import type { RoleCode } from './types';

export type PermissionAction =
  | 'VIEW_BALANCES'
  | 'CREATE_OBLIGATION'
  | 'MODIFY_OBLIGATION'
  | 'CONFIRM_PAYMENT'
  | 'REVERSE_PAYMENT'
  | 'RECONCILE_ACCOUNT'
  | 'REGISTER_TRANSFER'
  | 'REGISTER_DAILY_INCOME'
  | 'REGISTER_EXTERNAL_SETTLEMENT'
  | 'LINK_ATTACHMENT'
  | 'MODIFY_CATALOGS'
  | 'CREATE_MASTER'
  | 'DEFINE_SALARY'
  | 'DEFINE_RESERVE'
  | 'SIMULATE_INVESTMENT'
  | 'APPROVE_INVESTMENT'
  | 'APPROVE_SENSITIVE_CHANGE'
  | 'CLOSE_PERIOD'
  | 'REOPEN_PERIOD'
  | 'VIEW_AUDIT'
  | 'EXPORT_DATA'
  | 'MANAGE_USERS_ROLES'
  | 'MANAGE_DEPLOYMENTS';

export const RBAC_MATRIX: Record<PermissionAction, readonly RoleCode[]> = {
  VIEW_BALANCES: ['DIRECCION', 'TESORERIA', 'CONTADOR'],
  CREATE_OBLIGATION: ['DIRECCION', 'TESORERIA'],
  MODIFY_OBLIGATION: ['DIRECCION', 'TESORERIA'],
  CONFIRM_PAYMENT: ['DIRECCION', 'TESORERIA'],
  REVERSE_PAYMENT: ['DIRECCION', 'TESORERIA'],
  RECONCILE_ACCOUNT: ['TESORERIA'],
  REGISTER_TRANSFER: ['DIRECCION', 'TESORERIA'],
  REGISTER_DAILY_INCOME: ['DIRECCION', 'TESORERIA'],
  REGISTER_EXTERNAL_SETTLEMENT: ['DIRECCION', 'TESORERIA'],
  LINK_ATTACHMENT: ['DIRECCION', 'TESORERIA'],
  MODIFY_CATALOGS: ['DIRECCION', 'TESORERIA'],
  CREATE_MASTER: ['DIRECCION', 'TESORERIA'],
  DEFINE_SALARY: ['DIRECCION'],
  DEFINE_RESERVE: ['DIRECCION'],
  SIMULATE_INVESTMENT: ['DIRECCION', 'TESORERIA'],
  APPROVE_INVESTMENT: ['DIRECCION'],
  APPROVE_SENSITIVE_CHANGE: ['DIRECCION'],
  CLOSE_PERIOD: ['DIRECCION'],
  REOPEN_PERIOD: ['DIRECCION'],
  VIEW_AUDIT: ['DIRECCION', 'TESORERIA', 'CONTADOR'],
  EXPORT_DATA: ['DIRECCION', 'TESORERIA', 'CONTADOR'],
  MANAGE_USERS_ROLES: ['DIRECCION', 'ADMIN_TECNICO'],
  MANAGE_DEPLOYMENTS: ['ADMIN_TECNICO'],
};

export function hasPermission(roleCodes: readonly RoleCode[], action: PermissionAction): boolean {
  const allowed = RBAC_MATRIX[action];
  return roleCodes.some(code => allowed.includes(code));
}
